import { useState } from 'react';
import { Plus, Sparkles } from 'lucide-react';
import { api } from '../api';
import { addDaysISO } from '../format';
import type { AiResponse } from '../types';
import { Alert, Badge, Button, Card, Empty, useNotice } from '../ui';
import type { PageProps } from './Dashboard';

export default function Copilot({ event, onChanged }: PageProps) {
  const [prompt, setPrompt] = useState('');
  const [res, setRes] = useState<AiResponse | null>(null);
  const [busy, setBusy] = useState(false);
  const [added, setAdded] = useState<string[]>([]);
  const { notice, run } = useNotice();
  const go = async () => { setBusy(true); await run(async () => setRes(await api.plan(event.id, prompt))); setBusy(false); };
  const add = (c: AiResponse['plan']['checklist'][number]) => run(async () => {
    const due = [addDaysISO(7), event.date].sort()[0];
    await api.create(event.id, 'tasks', { title: c.title, category: c.category || 'general', priority: c.priority, due_date: due });
    setAdded((a) => [...a, c.title]);
  }, `Added "${c.title}" to your timeline.`, onChanged);
  return (
    <div className="space-y-5">
      <Card title={<span className="flex items-center gap-2"><Sparkles className="h-5 w-5 text-gold-500" aria-hidden />AI Event Copilot</span>}>
        <label className="block text-sm font-medium" htmlFor="ai-prompt">Ask for advice (optional)</label>
        <textarea id="ai-prompt" className="input mt-1" rows={3} maxLength={500} value={prompt} onChange={(e) => setPrompt(e.target.value)} placeholder="e.g. What should I prioritise this week? How do I keep decor affordable?" />
        <div className="mt-3 flex items-center gap-3"><Button variant="gold" onClick={go} loading={busy}>Generate plan from my event data</Button><span className="text-xs text-emerald-800/70">Uses your saved budget, tasks, vendors and guests.</span></div>
      </Card>
      {notice}
      {!res && !busy && <Card><Empty title="No plan generated yet" hint="Click generate to get recommendations grounded in this event." /></Card>}
      {res && <>
        <Alert kind={res.mode === 'gemini' ? 'success' : 'info'}>{res.mode === 'gemini' ? 'Generated by Gemini via the secure backend. Financial figures come from deterministic calculations.' : `Fallback mode: ${res.reason}`}</Alert>
        <Card title="Summary" action={<Badge tone={res.mode === 'gemini' ? 'good' : 'warn'}>{res.mode === 'gemini' ? 'Gemini' : 'Fallback (rule-based)'}</Badge>}><p>{res.plan.summary}</p></Card>
        <div className="grid gap-5 lg:grid-cols-2">
          <Card title="Recommendations"><ul className="list-disc space-y-2 pl-5 text-sm">{res.plan.recommendations.map((r, i) => <li key={i}>{r}</li>)}</ul></Card>
          <Card title="Risks"><ul className="list-disc space-y-2 pl-5 text-sm">{res.plan.risks.map((r, i) => <li key={i}>{r}</li>)}</ul></Card>
        </div>
        <Card title="Suggested checklist">
          {res.plan.checklist.length === 0 ? <Empty title="Nothing new to add" hint="Your timeline already covers the suggestions." /> :
            <ul className="divide-y divide-ivory-300">{res.plan.checklist.map((c) => (
              <li key={c.title} className="flex items-center justify-between gap-3 py-2 text-sm"><span>{c.title} <Badge tone={c.priority === 'high' ? 'bad' : 'neutral'}>{c.priority}</Badge></span>
                <Button variant="ghost" disabled={added.includes(c.title)} onClick={() => add(c)}><Plus className="h-4 w-4" aria-hidden />{added.includes(c.title) ? 'Added' : 'Add to tasks'}</Button></li>))}</ul>}
        </Card>
      </>}
    </div>
  );
}
